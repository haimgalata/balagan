/**
 * ONE-OFF generator: static catalog -> src/data/fallbackCatalog.ts
 *
 * The storefront's offline fallback (used when the database can't be reached and nothing is
 * cached, and by VITE_CATALOG_SOURCE=static) is a literal snapshot in the SAME shape the
 * database returns from get_storefront_catalog(). It goes through the exact same mapper as
 * live data, so there is a single code path and NO pack formula anywhere in the app.
 *
 * The migration rule (decision D2: package 'פקט' x10, regular = unit x 10, active sale =
 * unit x 10 - 10) is applied HERE, once, in exact integer agorot, to write literal per-product
 * numbers — identical to what supabase/seed.sql loaded. Regenerate only if the seed source changes.
 *
 * Run from the repo root:  node --no-warnings scripts/generate-fallback-catalog.mjs
 * Output is deterministic (no timestamps).
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { products } = await import(new URL("../src/data/products.ts", import.meta.url));
const { categories } = await import(new URL("../src/data/categories.ts", import.meta.url));

const UNITS_PER_PACKAGE = 10;
const PACKAGE_DISCOUNT_CENTS = 1000;
const PACKAGE_LABEL = "פקט";
const cents = (n) => Math.round(n * 100);
const fromCents = (c) => c / 100;
const subcategorySlugOf = (p) => p.subcategorySlug ?? p.brand.toLowerCase().replace(/\s+/g, "-");

// same render order as the storefront: category order, subcategory order, then array order inside a subcategory
const ordered = categories.flatMap((c) =>
  c.subcategories.flatMap((s) => products.filter((p) => p.category === c.slug && subcategorySlugOf(p) === s.slug))
);
if (ordered.length !== products.length) {
  console.error(`refusing to generate: ${products.length - ordered.length} product(s) do not belong to any subcategory`);
  process.exit(1);
}

const rpcCategories = categories.map((c) => ({
  id: c.id,
  slug: c.slug,
  name_he: c.name,
  name_en: null,
  subcategories: c.subcategories.map((s) => ({ id: s.id, slug: s.slug, name_he: s.name, name_en: null })),
}));

const rpcProducts = ordered.map((p) => {
  const u = cents(p.unitPrice);
  const regular = u * UNITS_PER_PACKAGE;
  const sale = regular - PACKAGE_DISCOUNT_CENTS;
  if (sale <= 0) throw new Error(`product ${p.id}: package sale would be <= 0`);
  return {
    id: p.id,
    category: p.category,
    subcategory: subcategorySlugOf(p),
    name_he: p.name,
    name_en: null,
    brand: p.brand,
    description: p.description ?? null,
    image_path: null,
    unit: { price: fromCents(u), sale_price: null, in_stock: p.inStock },
    package: { label: PACKAGE_LABEL, unit_count: UNITS_PER_PACKAGE, price: fromCents(regular), sale_price: fromCents(sale), in_stock: p.inStock },
  };
});

const src = `/**
 * OFFLINE FALLBACK CATALOG — GENERATED by scripts/generate-fallback-catalog.mjs. Do not edit by hand.
 *
 * A literal snapshot of the catalog in the exact shape the database returns from
 * get_storefront_catalog(). The storefront uses it (through the same mapper as live data) only when
 * the database can't be reached and nothing is cached, or when VITE_CATALOG_SOURCE=static.
 * Package prices are plain per-product data — nothing here or in the app computes them.
 */
import type { RpcCatalog } from "@/lib/catalogApi";

export const fallbackCatalog: RpcCatalog = {
  categories: ${JSON.stringify(rpcCategories, null, 2).replace(/\n/g, "\n  ")},
  products: [
${rpcProducts.map((p) => "    " + JSON.stringify(p)).join(",\n")},
  ],
};
`;

const outPath = resolve(root, "src", "data", "fallbackCatalog.ts");
writeFileSync(outPath, src, "utf8");
console.log(`wrote ${outPath} (${src.length} bytes): ${rpcCategories.length} categories, ${rpcProducts.length} products`);
